import { expect, test } from '@playwright/test'

test('grandma writing screen works at desktop and mobile sizes', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/grandma/story')
  await expect(page.getByRole('heading', { name: 'Soto Ayam' })).toHaveCount(0)
  await expect(page.getByLabel('Character panel')).toBeVisible()
  await expect(page.getByLabel('Written story panel')).toBeVisible()
  const leftPanel = await page.getByLabel('Character panel').boundingBox()
  const rightPanel = await page.getByLabel('Written story panel').boundingBox()
  expect(leftPanel?.width).toBeCloseTo(rightPanel?.width ?? 0, 0)
  await expect(page.getByLabel('Character panel').getByText(/First, toast the coconut/)).toBeAttached()
  await expect(page.getByLabel('Written story panel').getByText(/Then in goes the pork/)).toBeAttached()
  await expect(page.getByRole('img', { name: 'Moldable character writing with a silver pencil' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Tidy story' })).toHaveCSS('font-weight', '400')
  await expect(page.getByRole('button', { name: 'Tidy story' })).toHaveCSS('border-radius', '0px')
  await expect(page.getByLabel('Story actions')).toHaveCSS('border-radius', '0px')
  await page.waitForTimeout(4100)
  await page.screenshot({ path: 'output/grandma-story-writing.png', fullPage: true })
  await page.waitForTimeout(4400)
  await expect(page.getByText(/First, toast the coconut/)).toBeVisible()
  await page.screenshot({ path: 'output/grandma-story-desktop.png', fullPage: true })

  await page.getByRole('button', { name: 'Tidy story' }).click()
  await expect(page.getByRole('heading', { name: 'Balinese Minced Pork (Lelawar Bali)' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Restore full story' })).toBeVisible()

  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Soto Ayam' })).toHaveCount(0)
  await expect(page.getByLabel('Character panel')).toBeVisible()
  await expect(page.getByLabel('Written story panel')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Copy link' })).toBeVisible()
  await page.screenshot({ path: 'output/grandma-story-mobile.png', fullPage: true })
})
